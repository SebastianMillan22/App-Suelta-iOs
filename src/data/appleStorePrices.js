/**
 * Detecta el país y moneda del usuario en iOS de forma precisa.
 */
export function detectarPaisUsuarioIos() {
  if (typeof window === "undefined") return "Colombia";

  // 1. Código de país oficial de StoreKit si está disponible
  if (window.CdvPurchase?.store?.countryCode) {
    const code = String(window.CdvPurchase.store.countryCode).toUpperCase();
    if (ISO_A_PAIS_MAP[code]) return ISO_A_PAIS_MAP[code];
  }

  // 2. Moneda de producto cargado por StoreKit
  try {
    const store = window.CdvPurchase?.store;
    const prod = store?.get?.("suelta_sub_monthly") || store?.get?.("suelta_sub_annual");
    const currency = prod?.pricing?.currency;
    if (currency) {
      if (currency === "COP") return "Colombia";
      if (currency === "EUR") return "España";
      if (currency === "MXN") return "México";
      if (currency === "CLP") return "Chile";
      if (currency === "PEN") return "Perú";
      if (currency === "USD") return "Estados Unidos";
    }
  } catch (_) {}

  // 3. Zona horaria del dispositivo
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    if (tz && TIMEZONE_A_PAIS_MAP[tz]) {
      return TIMEZONE_A_PAIS_MAP[tz];
    }
  } catch (_) {}

  // 4. Idioma y región del sistema (navigator.languages / language)
  try {
    const navLangs = navigator.languages || [navigator.language];
    for (const lang of navLangs) {
      if (!lang) continue;
      const parts = lang.split(/[-_]/);
      if (parts.length >= 2) {
        const countryCode = parts[1].toUpperCase();
        if (ISO_A_PAIS_MAP[countryCode]) {
          return ISO_A_PAIS_MAP[countryCode];
        }
      }
    }
  } catch (_) {}

  // 5. Fallback por defecto: Colombia (moneda base de Suelta)
  return "Colombia";
}

